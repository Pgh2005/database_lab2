DROP DATABASE IF EXISTS online_shop;
CREATE DATABASE online_shop CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE online_shop;
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE categories (
  id        INT NOT NULL AUTO_INCREMENT,
  parent_id INT NULL,
  name      VARCHAR(100) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_categories_name (name),
  CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id) ON DELETE SET NULL
) ENGINE=InnoDB COMMENT='Product categories (tree: main category -> sub-category)';

CREATE TABLE brands (
  id      INT NOT NULL AUTO_INCREMENT,
  name    VARCHAR(100) NOT NULL,
  country VARCHAR(60) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_brands_name (name)
) ENGINE=InnoDB COMMENT='Brands / manufacturers / publishers';

CREATE TABLE products (
  id             INT NOT NULL AUTO_INCREMENT,
  category_id    INT NOT NULL,
  brand_id       INT NOT NULL,
  name           VARCHAR(200) NOT NULL,
  price          DECIMAL(10,2) NOT NULL,
  stock_quantity INT NOT NULL DEFAULT 0,
  is_active      TINYINT(1) NOT NULL DEFAULT 1,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_products_name (name),
  KEY idx_products_category (category_id),
  KEY idx_products_brand (brand_id),
  CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
  CONSTRAINT fk_products_brand    FOREIGN KEY (brand_id)    REFERENCES brands (id),
  CONSTRAINT chk_products_price CHECK (price >= 0),
  CONSTRAINT chk_products_stock CHECK (stock_quantity >= 0)
) ENGINE=InnoDB COMMENT='Products for sale';

CREATE TABLE customers (
  id            INT NOT NULL AUTO_INCREMENT,
  first_name    VARCHAR(60)  NOT NULL,
  last_name     VARCHAR(60)  NOT NULL,
  email         VARCHAR(150) NOT NULL,
  phone         VARCHAR(30)  NULL,
  address       VARCHAR(150) NULL,
  city          VARCHAR(80)  NULL,
  country       VARCHAR(60)  NULL,
  registered_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_customers_email (email)
) ENGINE=InnoDB COMMENT='Registered customers';

CREATE TABLE orders (
  id             INT NOT NULL AUTO_INCREMENT,
  customer_id    INT NOT NULL,
  order_date     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status         ENUM('pending','shipped','delivered','cancelled') NOT NULL DEFAULT 'pending',
  payment_method ENUM('credit_card','paypal','bank_transfer','cash_on_delivery') NOT NULL,
  total_amount   DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (id),
  KEY idx_orders_customer (customer_id),
  KEY idx_orders_date (order_date),
  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
) ENGINE=InnoDB COMMENT='Orders (one row per purchase)';

CREATE TABLE order_items (
  order_id   INT NOT NULL,
  product_id INT NOT NULL,
  quantity   INT NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (order_id, product_id),
  KEY idx_order_items_product (product_id),
  CONSTRAINT fk_order_items_order   FOREIGN KEY (order_id)   REFERENCES orders (id) ON DELETE CASCADE,
  CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT chk_order_items_qty CHECK (quantity > 0)
) ENGINE=InnoDB COMMENT='Items inside each order (orders <-> products, many-to-many); unit_price = price at purchase time';

CREATE TABLE reviews (
  id          INT NOT NULL AUTO_INCREMENT,
  product_id  INT NOT NULL,
  customer_id INT NOT NULL,
  rating      TINYINT NOT NULL,
  title       VARCHAR(100) NULL,
  comment     VARCHAR(255) NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_reviews_product_customer (product_id, customer_id),
  KEY idx_reviews_customer (customer_id),
  CONSTRAINT fk_reviews_product  FOREIGN KEY (product_id)  REFERENCES products (id) ON DELETE CASCADE,
  CONSTRAINT fk_reviews_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
  CONSTRAINT chk_reviews_rating CHECK (rating BETWEEN 1 AND 5)
) ENGINE=InnoDB COMMENT='Customer reviews of products (1-5 stars)';


